"""exp03 inputs: which rollouts each model contributes, and exp02's labels (read-only).

Rollouts per model:
- exp02 stage 1 (10 per Fortress question, 2 per benign twin, 2 per excluded eval-stating prompt)
- exp02 stage 2 on the top-20% questions: Qwen3 all 40 extra (indices 10..49), Qwen3.5 20 extra (10..29),
  Qwen3.8 exp02's 20 extra (10..29) plus exp03's 20 new ones (30..49, generated by exp03_generate.py)
"""

from __future__ import annotations

import json
from pathlib import Path
from types import SimpleNamespace

import exp03_config as cfg
import ladder_config as base


def exp02_generation_files(model: str) -> list[Path]:
    import ladder_generate

    extra = min(cfg.STAGE2_EXTRA_USED[model], 40)
    paths = ladder_generate.cache_paths(model, SimpleNamespace(smoke=False, stage2_extra=extra))
    if not paths["stage2"].exists():  # Qwen3.8's exp02 run had 20 extra
        paths["stage2"] = ladder_generate.cache_paths(model, SimpleNamespace(smoke=False, stage2_extra=20))["stage2"]
    missing = [p for p in (paths["stage1"], paths["stage2"]) if not p.exists()]
    if missing:
        raise FileNotFoundError(f"exp02 generations missing for {model}: {missing}")
    return [paths["stage1"], paths["stage2"]]


def qwen38_new_stage2_path() -> Path:
    model = "Qwen3.8-27B"
    stage1 = exp02_generation_files(model)[0]
    key = base.content_key({"exp02_stage1": stage1.stem, "indices": [cfg.QWEN38_NEW_STAGE2.start,
                            cfg.QWEN38_NEW_STAGE2.stop], "mtp": cfg.MTP_SPECULATIVE_TOKENS})
    return cfg.GENERATIONS_DIR / f"{model}_{key}_stage2_idx{cfg.QWEN38_NEW_STAGE2.start}-{cfg.QWEN38_NEW_STAGE2.stop - 1}.jsonl"


def added_ladder_paths(model: str) -> dict[str, Path]:
    """exp03's own stage 1 / selection / stage 2 for a LADDER_MODELS_ADDED model: exp02's file names (same design
    key), in exp03's generations folder."""
    import ladder_generate

    exp02 = ladder_generate.cache_paths(model, SimpleNamespace(smoke=False, stage2_extra=cfg.STAGE2_EXTRA_USED[model]))
    return {k: cfg.GENERATIONS_DIR / exp02[k].name for k in ("stage1", "selection", "stage2", "timing")}


def generation_files(model: str, exp02_only: bool = False) -> list[Path]:
    if model in cfg.LADDER_MODELS_ADDED:
        if exp02_only:
            raise ValueError(f"{model} has no exp02 rollouts")
        paths = added_ladder_paths(model)
        missing = [p for p in (paths["stage1"], paths["stage2"]) if not p.exists()]
        if missing:
            raise FileNotFoundError(f"{missing} missing; run exp03_generate.py ladder-added --models {model} first")
        return [paths["stage1"], paths["stage2"]]
    files = exp02_generation_files(model)
    if model == "Qwen3.8-27B" and not exp02_only:
        new = qwen38_new_stage2_path()
        if not new.exists():
            raise FileNotFoundError(f"{new} missing; run exp03_generate.py stage2 first")
        files.append(new)
    return files


def load_rollouts(model: str, drop_token_ids: bool = True, exp02_only: bool = False) -> list[dict]:
    last_index = base.STAGE1_ROLLOUTS + cfg.STAGE2_EXTRA_USED[model]
    rows = []
    for path in generation_files(model, exp02_only):
        for line in path.open():
            r = json.loads(line)
            if r["stage"] == "stage2" and r["rollout_index"] >= last_index:
                continue
            if drop_token_ids:
                r.pop("cot_token_ids", None)
                r.pop("answer_token_ids", None)
            rows.append(r)
    return rows


def rollout_key(r: dict) -> str:
    return f"{r['model']}|{r['prompt_set']}|{r['item_id']}|{r['stage']}|{r['rollout_index']}"


def prompt_texts() -> dict[tuple[str, str], str]:
    texts = {}
    for line in base.PROMPTS_PATH.open():
        row = json.loads(line)
        texts[(row["prompt_set"], row["item_id"])] = row["text"]
    return texts


def exp02_main_labels(model: str) -> dict[tuple[str, str], dict]:
    """exp02 judge outputs, {(rollout_key, call): row}, main variant only."""
    import ladder_judge

    path = ladder_judge.label_path(model, smoke=False)
    return {(r["rollout_key"], r["call"]): r for r in map(json.loads, path.open()) if r["variant"] == "main"}
